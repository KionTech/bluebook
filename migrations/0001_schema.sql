-- Bluebook's schema: the app tables of the Laravel database (the SDE
-- universe and dogma tables are not used and not carried over), plus the
-- sessions, the throttle keys and the job queue that replace Laravel's
-- session, cache and queue tables.
--
-- Names sort under the ICU root collation, close to MySQL's
-- utf8mb4_unicode_ci order (case-insensitive first, accents next);
-- lookups by name never use equality. EVE ids are bigint. Every time is
-- UTC (timestamptz).

create table alliances (
    id bigint primary key,
    name text collate "und-x-icu",
    ticker text collate "und-x-icu",
    creator_id bigint,
    creator_corporation_id bigint,
    faction_id bigint,
    date_founded timestamptz,
    created_at timestamptz,
    updated_at timestamptz
);

create table corporations (
    id bigint primary key,
    name text collate "und-x-icu",
    ticker text collate "und-x-icu",
    -- NPC corporations point at SDE rows (CEO stubs, stations, factions)
    -- that are not carried over, so these stay plain columns.
    ceo_id bigint,
    creator_id bigint,
    faction_id bigint,
    alliance_id bigint references alliances (id),
    home_station_id bigint,
    member_count bigint,
    shares bigint,
    date_founded timestamptz,
    description text,
    url text,
    tax_rate double precision,
    war_eligible boolean,
    npc boolean not null default false,
    created_at timestamptz,
    updated_at timestamptz
);

create index corporations_name_index on corporations (name);
create index corporations_ticker_index on corporations (ticker);
create index corporations_alliance_id_index on corporations (alliance_id);

-- The names of faction contacts, static data from the SDE.
create table factions (
    id bigint primary key,
    name text not null collate "und-x-icu",
    created_at timestamptz,
    updated_at timestamptz
);

create table users (
    id bigint generated by default as identity primary key,
    name text not null collate "und-x-icu",
    -- The foreign key follows the characters table.
    main_character_id bigint,
    -- The first-login wizard was finished or skipped.
    setup_completed_at timestamptz,
    created_at timestamptz not null,
    updated_at timestamptz not null
);

-- Registered characters, the character contacts of the source and the
-- CEO stubs of NPC corporations: one row per EVE character the app knows.
create table characters (
    id bigint primary key,
    name text collate "und-x-icu",
    corporation_id bigint references corporations (id),
    alliance_id bigint references alliances (id),
    user_id bigint references users (id) on delete set null,
    character_owner_hash text,
    should_sync boolean not null default false,
    created_at timestamptz,
    updated_at timestamptz
);

create index characters_user_id_index on characters (user_id);
create index characters_corporation_id_index on characters (corporation_id);
create index characters_alliance_id_index on characters (alliance_id);

alter table users
    add constraint users_main_character_id_foreign
    foreign key (main_character_id) references characters (id) on delete set null;

-- EVE SSO tokens, the scopes each carries folded in. Refresh tokens rotate
-- on every refresh; the newest token of a character with a scope is used.
create table esi_tokens (
    id bigint generated by default as identity primary key,
    character_id bigint not null references characters (id) on delete cascade,
    access_token text not null,
    token_type text not null,
    refresh_token text not null,
    character_owner_hash text not null,
    scopes text[] not null default '{}',
    expires_at timestamptz not null,
    created_at timestamptz not null,
    updated_at timestamptz not null
);

create index esi_tokens_character_id_index on esi_tokens (character_id);

-- The canonical standings: the source's contacts.
create table source_contacts (
    id bigint generated by default as identity primary key,
    contact_id bigint not null unique,
    contact_type text not null
        check (contact_type in ('character', 'corporation', 'alliance', 'faction')),
    standing numeric(4, 2) not null,
    created_at timestamptz not null,
    updated_at timestamptz not null
);

-- What the sync last wrote to each character's contact list.
create table character_synced_contacts (
    id bigint generated by default as identity primary key,
    character_id bigint not null references characters (id) on delete cascade,
    contact_id bigint not null,
    standing numeric(4, 2) not null,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    unique (character_id, contact_id)
);

-- The one standings source.
create table standings_sources (
    id bigint generated by default as identity primary key,
    type text not null check (type in ('character', 'corporation', 'alliance')),
    entity_id bigint not null,
    last_synced_at timestamptz,
    created_at timestamptz not null,
    updated_at timestamptz not null
);

create unique index standings_sources_singleton on standings_sources ((true));

create table standing_requests (
    id bigint generated by default as identity primary key,
    subject_type text not null check (subject_type in ('character', 'corporation', 'alliance')),
    subject_id bigint not null,
    requested_by_character_id bigint not null references characters (id) on delete cascade,
    status text not null default 'pending' check (status in ('pending', 'done', 'rejected')),
    created_at timestamptz not null,
    updated_at timestamptz not null,
    unique (subject_type, subject_id)
);

create index standing_requests_status_index on standing_requests (status);
create index standing_requests_requested_by_index on standing_requests (requested_by_character_id);

-- The Discord webhook and role, overriding DISCORD_STANDING_REQUEST_WEBHOOK.
create table discord_settings (
    id bigint generated by default as identity primary key,
    webhook_url text,
    role_id text,
    created_at timestamptz not null,
    updated_at timestamptz not null
);

create unique index discord_settings_singleton on discord_settings ((true));

-- Sign-ins: the SHA-256 of the cookie's token, the user (none for a
-- guest's session) and the few values the session carries (the active
-- character, the intended URL, the add-to-account flag, the flash).
create table sessions (
    id text primary key,
    user_id bigint references users (id) on delete cascade,
    data jsonb not null default '{}',
    last_activity timestamptz not null,
    created_at timestamptz not null
);

create index sessions_user_id_index on sessions (user_id);

-- Keys that hold something back until they expire: the hourly
-- "source unreadable" alert and the mail to a lapsed character.
create table throttles (
    key text primary key,
    expires_at timestamptz not null
);

-- The background jobs: character syncs, EVE mails and Discord messages.
create table jobs (
    id bigint generated by default as identity primary key,
    kind text not null,
    payload jsonb not null,
    available_at timestamptz not null,
    reserved_at timestamptz,
    attempts integer not null default 0,
    failed_at timestamptz,
    last_error text,
    created_at timestamptz not null
);

create index jobs_due_index on jobs (available_at, id) where failed_at is null and reserved_at is null;
